#!/usr/bin/env python3
"""Writes docs/catalog.md: every operation in the embedded catalog, grouped by OpenAPI tag.

    python3 scripts/gen_catalog_doc.py

Run it after regenerating internal/cloudflare/catalog.json.gz.
"""
import collections
import gzip
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
CATALOG = ROOT / "internal/cloudflare/catalog.json.gz"
OUT = ROOT / "docs/catalog.md"


def main():
    with gzip.open(CATALOG, "rt") as f:
        ops = json.load(f)
    groups = collections.defaultdict(list)
    for op in ops:
        groups[(op.get("t") or ["Other"])[0]].append(op)

    lines = [
        "---",
        "outline: false",
        "---",
        "",
        "# Operation catalog",
        "",
        f"All {len(ops):,} operation tools, grouped by the area Cloudflare's schema puts them in "
        f"({len(groups)} areas). Generated by `scripts/gen_catalog_doc.py` from the embedded catalog; "
        "use the search box to find one, or ask `find`.",
        "",
    ]
    for tag in sorted(groups, key=str.lower):
        lines += [f"## {tag}", "", "| Tool | Method | Path |", "|---|---|---|"]
        for op in sorted(groups[tag], key=lambda o: o["n"]):
            path = op["p"].replace("|", "\\|")
            lines.append(f"| `{op['n']}` | {op['m']} | `{path}` |")
        lines.append("")
    OUT.write_text("\n".join(lines))
    print(f"{OUT.relative_to(ROOT)}: {len(ops)} operations, {len(groups)} areas")


if __name__ == "__main__":
    main()
